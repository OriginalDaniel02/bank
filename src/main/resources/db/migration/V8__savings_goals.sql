CREATE TABLE savings_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(50) NOT NULL,
    type VARCHAR(20) NOT NULL,
    target_amount NUMERIC(19, 2) NOT NULL,
    saved_amount NUMERIC(19, 2) NOT NULL DEFAULT 0,
    deadline DATE,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_savings_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT ck_savings_saved_not_negative CHECK (saved_amount >= 0)
);
CREATE INDEX idx_savings_user ON savings_goals(user_id, status);
